/** 평가서 한 게임 분량 HTML (모달·인쇄 공용) */
function reviewHTML(n) {
  const r = REVIEWS[n], g = GAMES[n];
  if (!r) return '<p>준비 중</p>';
  const cnt = { O: 0, '△': 0, X: 0 };
  REVIEW_CRITERIA.forEach(c => cnt[r.marks[c.key].m]++);
  return `
  <div class="rv">
    <header class="rv-head">
      <div>
        <p class="rv-kicker">${pad2(n)} · 기획 ${g.who}</p>
        <h4>${g.title}</h4>
      </div>
      <div class="rv-count"><span class="good">○ ${cnt.O}</span><span class="warn">△ ${cnt['△']}</span><span class="bad">✕ ${cnt.X}</span></div>
    </header>
    <p class="rv-sum">${r.summary}</p>

    <h5 class="rv-h">여섯 가지로 본 이 게임</h5>
    <div class="rv-marks">${REVIEW_CRITERIA.map(c => {
      const m = r.marks[c.key], M = REVIEW_MARK[m.m];
      return `<div class="rv-mark ${M.cls}"><span class="sym">${M.sym}</span><div><b>${c.name}</b><p>${m.note}</p></div></div>`;
    }).join('')}</div>

    <h5 class="rv-h">고쳐 볼 곳</h5>
    ${r.bugs.map(b => `
      <section class="rv-bug">
        <p class="rv-lv">${b.level}순위</p>
        <h6>${b.title}</h6>
        <dl>
          <dt>테스트에서</dt><dd>${b.found}</dd>
          <dt>왜 문제인가</dt><dd>${b.why}</dd>
          <dt>이렇게 따져 보기</dt><dd><ol>${b.fix.map(f => `<li>${f}</li>`).join('')}</ol></dd>
        </dl>
      </section>`).join('')}

    <h5 class="rv-h">기획서에 없어서 AI가 정한 값 <small>원래 기획자가 정할 것</small></h5>
    <table class="rv-table">
      <thead><tr><th>빈 곳</th><th>정한 값</th><th>이유</th></tr></thead>
      <tbody>${r.missing.map(x => `<tr><td>${x.item}</td><td class="v">${x.decided}</td><td>${x.why}</td></tr>`).join('')}</tbody>
    </table>
  </div>`;
}
